export default function BookCheckout({ lang, d }: Props) {
  const t = copy[lang];
  const [edition, setEdition] = useState<Locale>(lang);
  const [receipt, setReceipt] = useState<File | null>(null);
  const [status, setStatus] = useState<CheckoutStatus>('idle');
  const [message, setMessage] = useState('');
  const [result, setResult] = useState<VerificationResponse | null>(null);
  const [checkingStep, setCheckingStep] = useState(0);
  const [copied, setCopied] = useState(false);
  const [hasSavedAccess, setHasSavedAccess] = useState(false);
  const fileRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    if (status !== 'checking') return;

    const timer = window.setInterval(() => {
      setCheckingStep((current) => (current + 1) % t.checking.length);
    }, 1800);

    return () => window.clearInterval(timer);
  }, [status, t.checking.length]);

  const restoreAccess = useCallback(async (editionToRestore: Locale, accessPass: string) => {
    const endpoint = process.env.NEXT_PUBLIC_RECEIPT_VERIFY_URL;
    if (!endpoint) return;

    setStatus('restoring');
    setMessage('');
    setResult(null);

    try {
      const response = await fetch(refreshEndpoint(endpoint), {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ accessPass, uiLanguage: lang }),
      });
      const payload = (await response.json()) as VerificationResponse;
      if (!response.ok || !payload.approved || !payload.downloadUrl) {
        removeStoredAccess(editionToRestore);
        setHasSavedAccess(false);
        setStatus('idle');
        setMessage('');
        return;
      }

      setHasSavedAccess(true);
      setResult(payload);
      setMessage(payload.message ?? t.restored);
      setStatus('approved');
    } catch {
      setHasSavedAccess(true);
      setStatus('idle');
      setMessage(t.restoreFailed);
    }
  }, [lang, t.restoreFailed, t.restored]);

  useEffect(() => {
    const accessPass = readStoredAccess()[edition];
    if (!accessPass) return;
    let cancelled = false;

    void Promise.resolve().then(() => {
      if (cancelled) return;
      setHasSavedAccess(true);
      return restoreAccess(edition, accessPass);
    });
    return () => { cancelled = true; };
  }, [edition, restoreAccess]);

  const validateFile = (file: File) => {
    const allowed = ['image/jpeg', 'image/png', 'image/webp', 'application/pdf'];
    return allowed.includes(file.type) && file.size > 0 && file.size <= MAX_FILE_BYTES;
  };

  const selectFile = (file: File | undefined) => {
    setResult(null);
    setMessage('');
    setStatus('idle');

    if (!file || !validateFile(file)) {
      setReceipt(null);
      setMessage(t.invalidFile);
      return;
    }

    setReceipt(file);
  };

  const copyAddress = async () => {
    await navigator.clipboard.writeText(SHAM_CASH_ADDRESS);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1800);
  };

  const submit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();

    if (!receipt || !validateFile(receipt)) {
      setMessage(t.invalidFile);
      return;
    }

    const endpoint = process.env.NEXT_PUBLIC_RECEIPT_VERIFY_URL;
    if (!endpoint) {
      setStatus('error');
      setMessage(t.config);
      return;
    }

    const form = new FormData(event.currentTarget);
    form.set('receipt', receipt);
    form.set('bookLanguage', edition);
    form.set('uiLanguage', lang);

    setStatus('checking');
    setCheckingStep(0);
    setMessage('');
    setResult(null);

    try {
      const response = await fetch(endpoint, { method: 'POST', body: form });
      const payload = (await response.json()) as VerificationResponse;

      if (payload.approved && payload.accessPass) {
        storeAccess(edition, payload.accessPass);
        setHasSavedAccess(true);
      }

      setResult(payload);
      setMessage(payload.message ?? (payload.approved ? t.ready : t.failed));
      setStatus(payload.approved && payload.downloadUrl ? 'approved' : 'rejected');
    } catch {
      setStatus('error');
      setMessage(t.failed);
    }
  };

  const reset = () => {
    setReceipt(null);
    setResult(null);
    setMessage('');
    setStatus('idle');
    if (fileRef.current) fileRef.current.value = '';
  };

  const changeEdition = (nextEdition: Locale) => {
    setEdition(nextEdition);
    setReceipt(null);
    setResult(null);
    setMessage('');
    setStatus('idle');
    setHasSavedAccess(Boolean(readStoredAccess()[nextEdition]));
    if (fileRef.current) fileRef.current.value = '';
  };

  const openMyBook = () => {
    const accessPass = readStoredAccess()[edition];
    if (accessPass) void restoreAccess(edition, accessPass);
  };

  const editions = [
    { id: 'en' as const, label: t.english, pages: 261, cover: englishCover },
    { id: 'ar' as const, label: t.arabic, pages: 258, cover: arabicCover },
  ];

  return (
    <div className={styles.page}>
      <header className={styles.hero}>
        <div className={`container ${styles.heroInner}`}>
          <div className={styles.eyebrow}><span />{t.eyebrow}</div>
          <h1>{t.title}</h1>
          <p>{t.intro}</p>
          {hasSavedAccess && (
            <button className={styles.myBook} type="button" onClick={openMyBook}>
              {t.myBook} →
            </button>
          )}
          <div className={styles.price}><span>$</span>2.99 <small>USD</small></div>
        </div>
      </header>

      <form className={`container ${styles.checkout}`} onSubmit={submit}>
        <section className={styles.section} aria-labelledby="edition-heading">
          <div className={styles.sectionHeading}>
            <h2 id="edition-heading">{t.choose}</h2>
            <span>{edition.toUpperCase()}</span>
          </div>
          <div className={styles.editions}>
            {editions.map((item) => (
              <label key={item.id} className={`${styles.edition} ${edition === item.id ? styles.editionSelected : ''}`}>
                <input
                  type="radio"
                  name="edition"
                  value={item.id}
                  checked={edition === item.id}
                  onChange={() => changeEdition(item.id)}
                />
                <Image src={item.cover} alt="" className={styles.cover} sizes="(max-width: 600px) 38vw, 150px" />
                <span className={styles.editionCopy}>
                  <strong>{item.label}</strong>
                  <small>{item.pages} {t.pages} · PDF</small>
                </span>
                <span className={styles.selectionMark} aria-hidden="true" />
              </label>
            ))}
          </div>
        </section>

        <section className={styles.section} aria-labelledby="payment-heading">
          <div className={styles.sectionHeading}>
            <h2 id="payment-heading">{t.payment}</h2>
            <span>SHAM CASH</span>
          </div>
          <div className={styles.paymentGrid}>
            <div className={styles.qrPanel}>
              <Image src={qrImage} alt={lang === 'ar' ? 'رمز شام كاش الخاص بفينوس العربيد' : 'Venus Alarbeed Sham Cash payment QR'} priority />
              <p>{t.scan}</p>
            </div>
            <div className={styles.paymentDetails}>
              <dl>
                <div><dt>{t.amount}</dt><dd>$2.99 / $3.00 / $3.10 USD</dd></div>
                <div><dt>{t.recipient}</dt><dd>{d.hero.nameFirst} {d.hero.nameLast}</dd></div>
                <div className={styles.addressRow}>
                  <dt>{t.address}</dt>
                  <dd><code>{SHAM_CASH_ADDRESS}</code><button type="button" onClick={copyAddress}>{copied ? t.copied : t.copy}</button></dd>
                </div>
              </dl>
              <p className={styles.exactNote}>{t.exact}</p>
            </div>
          </div>
        </section>

        <section id="my-book" className={styles.section} aria-labelledby="receipt-heading">
          <div className={styles.sectionHeading}>
            <h2 id="receipt-heading">{t.receipt}</h2>
            <span>{t.automatic}</span>
          </div>

          <label className={`${styles.upload} ${receipt ? styles.uploadReady : ''}`}>
            <input
              ref={fileRef}
              type="file"
              name="receipt"
              accept="image/jpeg,image/png,image/webp,application/pdf,.jpg,.jpeg,.png,.webp,.pdf"
              required
              onChange={(event) => selectFile(event.target.files?.[0])}
            />
            <span className={styles.uploadIcon} aria-hidden="true">
              {receipt ? '✓' : '↑'}
            </span>
            <strong>{receipt?.name ?? t.upload}</strong>
            <small>{receipt ? `${(receipt.size / 1024 / 1024).toFixed(2)} MB · ${t.replace}` : t.formats}</small>
          </label>

          <label className={styles.confirmation}>
            <input name="confirmation" type="checkbox" required />
            <span>{t.confirm}</span>
          </label>

          {message && status !== 'approved' && (
            <div className={`${styles.notice} ${status === 'rejected' || status === 'error' ? styles.noticeError : ''}`} role="alert">
              {message}
            </div>
          )}

          {status === 'checking' || status === 'restoring' ? (
            <div className={styles.checking} aria-live="polite">
              <span className={styles.spinner} />
              <strong>{status === 'restoring' ? t.restoring : t.checking[checkingStep]}</strong>
              <div><span style={{ width: status === 'restoring' ? '72%' : `${34 + checkingStep * 30}%` }} /></div>
            </div>
          ) : status === 'approved' && result?.downloadUrl ? (
            <div className={styles.approved} role="status">
              <span className={styles.approvedMark}>✓</span>
              <div>
                <h3>{t.approved}</h3>
                <p>{message || t.ready}</p>
                {result.receipt?.transactionNumber && <small>#{result.receipt.transactionNumber}</small>}
              </div>
              <div className={styles.approvedActions}>
                {result.readUrl && <a className="btn btn-ghost-light" href={result.readUrl} target="_blank" rel="noreferrer">{t.read} ↗</a>}
                <a className="btn btn-ghost-light" href={result.downloadUrl}>{t.download} ↓</a>
              </div>
            </div>
          ) : (
            <div className={styles.submitRow}>
              <button className={`btn ${styles.submit}`} type="submit">{t.submit} →</button>
              {(status === 'rejected' || status === 'error') && (
                <button className={styles.retry} type="button" onClick={reset}>{t.retry}</button>
              )}
            </div>
          )}

          <p className={styles.privacy}>{t.privacy}</p>
        </section>
      </form>
    </div>
  );
}
